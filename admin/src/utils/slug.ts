/** Maktab nomidan URL-xavfsiz slug yasaydi: "5-sonli maktab" -> "5-sonli-maktab". */
export function slugify(input: string): string {
  return input
    .toLowerCase()
    .replace(/[ʻʼ'`’‘]/g, '') // o'zbek apostroflari: o'g'il -> ogil
    .replace(/[Ѐ-ӿ]/g, (ch) => CYRILLIC[ch] ?? '')
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60)
}

export const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/
